export type MetricSource = "FPL API" | "Derived";

export interface MetricDefinition {
  displayName: string;
  internalName: string;
  source: MetricSource;
  apiFields: string[];
  suppliedByFPL: boolean;
  derived: boolean;
  formula: string | null;
  units: string | null;
  caveats: string | null;
  availabilityNote: string;
}

function def(d: MetricDefinition): MetricDefinition {
  return d;
}

