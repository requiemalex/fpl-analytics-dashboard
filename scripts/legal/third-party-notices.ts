/**
 * Writes client/src/legal/third-party-notices.txt: the licence of every
 * open-source package that ships inside the app (the client and server
 * bundles, electron-updater, and Electron itself), with its copyright
 * notice. Most of these licences (MIT, ISC, BSD) let us bundle the code on
 * one condition: their notice goes with it. The About & Legal page
 * (client/src/pages/Legal.tsx) builds the file into the app and shows it,
 * so it ships with every copy.
 *
 * Run by `npm run legal:notices`, and by `electron:build` before every
 * desktop build, so a dependency change can never ship without its notice.
 */
import { execSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

interface LsNode {
  version?: string;
  path?: string;
  dependencies?: Record<string, LsNode>;
}

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const out = join(root, "client", "src", "legal", "third-party-notices.txt");

/** Our own workspace packages: our code, under our own licence (LICENSE.txt). */
const OWN = new Set(["scoutline-client", "scoutline-server"]);

const tree = JSON.parse(execSync("npm ls --all --omit=dev --long --json", { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })) as LsNode;

const packages = new Map<string, { name: string; version: string; path: string }>();
function walk(node: LsNode) {
  for (const [name, child] of Object.entries(node.dependencies ?? {})) {
    if (!child.version || !child.path) continue;
    const key = `${name}@${child.version}`;
    if (packages.has(key)) continue;
    if (!OWN.has(name)) packages.set(key, { name, version: child.version, path: child.path });
    walk(child);
  }
}
walk(tree);

// Electron is a build tool to npm (a devDependency), but its runtime is what
// the desktop app runs on, so its notice ships too. Chromium's own notices
// ship beside it as LICENSES.chromium.html (electron-builder adds that file).
const electronPath = join(root, "node_modules", "electron");
if (existsSync(electronPath)) {
  const version = (JSON.parse(readFileSync(join(electronPath, "package.json"), "utf8")) as { version: string }).version;
  packages.set(`electron@${version}`, { name: "electron", version, path: electronPath });
}

function licenceText(dir: string): string | null {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|-|$)/i.test(f));
  return file ? readFileSync(join(dir, file), "utf8").trim() : null;
}

function licenceName(dir: string): string {
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8")) as { license?: string | { type?: string }; licenses?: { type?: string }[] };
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license?.type) return pkg.license.type;
  if (pkg.licenses?.length) return pkg.licenses.map((l) => l.type ?? "unknown").join(" OR ");
  return "unknown";
}

const sections = [...packages.values()]
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
  .map((p) => {
    const text = licenceText(p.path);
    return [`${p.name} ${p.version}`, `Licence: ${licenceName(p.path)}`, "", text ?? "(No licence file is included in this package; its licence is the one named above.)"].join("\n");
  });

const header = `Scoutline includes the open-source software listed below. Each package is the
property of its authors and is used under the licence shown with it. These
notices are reproduced as those licences require.

${packages.size} packages. Generated by scripts/legal/third-party-notices.ts.`;

writeFileSync(out, `${header}\n\n${"=".repeat(78)}\n\n${sections.join(`\n\n${"-".repeat(78)}\n\n`)}\n`);
console.log(`Wrote ${packages.size} notices to ${out}`);
